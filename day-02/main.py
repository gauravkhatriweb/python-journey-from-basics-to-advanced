#Variables
#A variable is a container for storing data
#You can create a variable and assign a value to it
name = "Alice"
age = 30
height = 1.75
#You can also change the value of a variable
name = "Bob"
age = 25
height = 1.80
#You can also create multiple variables in one line
x, y, z = 1, 2, 3
#You can also use the same variable name to store different types of data
data = "Hello"
data = 123
data = 3.14
#Variables Rules
#Variable names must start with a letter or an underscore
#Variable names can only contain letters, numbers, and underscores
#Variable names cannot be a reserved keyword
#Variable names are case-sensitive
#Examples of valid variable names
my_variable = 10
_variable = 20
myVariable = 30
#Examples of invalid variable names
#1variable = 10 #Starts with a number
#my-variable = 20 #Contains a hyphen
#my variable = 30 #Contains a space
#my-variable = 40 #Contains a hyphen
#my variable = 50 #Contains a space

#Naming Conventions
#In Python, there are several naming conventions for variables
#1. snake_case: This convention uses lowercase letters and underscores to separate words. Example:
my_variable = 10
#2. camelCase: This convention uses lowercase letters for the first word and uppercase letters for the first letter of each subsequent word. Example:
myVariable = 20
#3. PascalCase: This convention uses uppercase letters for the first letter of each word.
MyVariable = 30
#4. UPPERCASE: This convention uses uppercase letters for all letters. Example:
MY_VARIABLE = 40
#The most commonly used naming convention in Python is snake_case, so it is recommended to use
#that convention for variable names.



